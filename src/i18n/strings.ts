const HIJRI_LATIN = ['Muharram', 'Safar', 'Rabi I', 'Rabi II', 'Jumada I', 'Jumada II', 'Rajab', 'Shaban', 'Ramadan', 'Shawwal', 'Dhul Qadah', 'Dhul Hijjah'];
const HIJRI_FR = ['Mouharram', 'Safar', 'Rabi I', 'Rabi II', 'Joumada I', 'Joumada II', 'Rajab', 'Chaabane', 'Ramadan', 'Chawwal', 'Dhou al-Qida', 'Dhou al-Hijja'];

export function hijriMonths(lang: Lang): string[] {
  return lang === 'ar' ? HIJRI_AR : lang === 'fr' ? HIJRI_FR : HIJRI_LATIN;
}
